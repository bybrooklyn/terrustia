//! Multi-tile objects: how big each one is and how its frames are laid out.
//!
//! `TileObjectData.Initialize` sets these up imperatively rather than as a table, mutating a
//! shared "current object" and stamping it into a slot, so the numbers here are the end state of
//! running that method rather than anything written down in it. A chest is two by two anchored at
//! its bottom-left, a door one by three anchored at its top, and placing either at the wrong
//! origin puts furniture through the floor.
//!
//! `full_width` and `full_height` are `CoordinateFullWidth`/`CoordinateFullHeight`: the size of one
//! style's block in the sprite sheet, which is what a style index is multiplied by to find its
//! frames. Both count the padding after every row and column, not between them, and both carry
//! `CoordinatePaddingFix` on top.
//!
//! Vanilla also gives most of these a set of sub-tiles (per style) and alternates (per placement
//! direction), which change anchors and liquid rules but never the geometry or the style layout.
//! Neither is modelled here; nothing this server does with an object needs them.
//!
//! Generated by `terrustia-codegen` from Terraria 1.4.5.7. Do not edit by hand.

/// The shape of one placeable object.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct TileObject {
    /// Size in tiles.
    pub width: i32,
    pub height: i32,
    /// Which tile of the object the player's cursor is on when they place it.
    pub origin: (i32, i32),
    /// Sprite-sheet geometry.
    pub coord_width: i32,
    pub coord_heights: &'static [i32],
    pub padding: i32,
    pub full_width: i32,
    pub full_height: i32,
    /// How styles are laid out in the sheet.
    pub style_horizontal: bool,
    pub style_multiplier: i32,
    pub style_wrap: i32,
    pub style_line_skip: i32,
    pub style_base: i32,
}

impl TileObject {
    /// The frame position of a given style, as `(x, y)` in the sheet.
    ///
    /// Styles run along one axis and wrap onto a new line after `style_wrap` of them, skipping
    /// `style_line_skip` rows each time, which is why a door's styles run down the sheet three
    /// rows at a time and a table's run across it. `TileObject.Place` (`TileObject.cs:57-76`),
    /// with `style * style_multiplier + style_base` from `CalculatePlacementStyle`
    /// (`TileObjectData.cs:1990-1997`).
    pub fn frame_of(&self, style: i32, random: i32) -> (i32, i32) {
        let mut index = style * self.style_multiplier + self.style_base;
        if random >= 0 {
            index += random;
        }
        let mut line = 0;
        if self.style_wrap > 0 {
            line = index / self.style_wrap * self.style_line_skip;
            index %= self.style_wrap;
        }
        if self.style_horizontal {
            (self.full_width * index, self.full_height * line)
        } else {
            (self.full_width * line, self.full_height * index)
        }
    }

    /// Which style a frame belongs to: the inverse of [`Self::frame_of`].
    ///
    /// This is what turns a mined object back into the item that placed it: the frame is all the
    /// world stores, and every table that says what a chair is worth is indexed by style.
    ///
    /// The frame given must be the object's *top-left* one. Any other cell of it is offset by
    /// where in the object it sits, which is what [`origin_of`] undoes.
    pub fn style_of(&self, frame_x: i16, frame_y: i16) -> i32 {
        if self.full_width == 0 || self.full_height == 0 {
            return 0;
        }
        let across = i32::from(frame_x) / self.full_width;
        let down = i32::from(frame_y) / self.full_height;
        // One axis carries the style and the other counts lines, and which is which is the
        // object's own business: a door's styles run down the sheet, a table's across it.
        let (index, line) = if self.style_horizontal {
            (across, down)
        } else {
            (down, across)
        };
        let index = if self.style_wrap > 0 && self.style_line_skip > 0 {
            index + line / self.style_line_skip * self.style_wrap
        } else {
            index
        };
        let multiplier = self.style_multiplier.max(1);
        (index - self.style_base).div_euclid(multiplier)
    }
}

/// Walk back from any cell of a multi-tile object to its top-left one.
///
/// A player mining a table hits whichever tile the cursor was over; everything that decides what
/// a table is worth starts from its corner. The frame says how far in the cell sits.
pub fn origin_of(block: u16, frame_x: i16, frame_y: i16) -> Option<(i32, i32)> {
    let object = tile_object(block)?;
    if object.full_width == 0 || object.full_height == 0 {
        return Some((0, 0));
    }
    let coord = object.coord_width + object.padding;
    let across = if coord > 0 {
        (i32::from(frame_x) % object.full_width) / coord
    } else {
        0
    };
    // Rows can differ in height, so walking down them is a subtraction rather than a division.
    let mut left = i32::from(frame_y) % object.full_height;
    let mut down = 0;
    for height in object.coord_heights {
        if left < height + object.padding {
            break;
        }
        left -= height + object.padding;
        down += 1;
    }
    Some((across.min(object.width - 1), down.min(object.height - 1)))
}

