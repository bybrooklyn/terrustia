/// `TileObjectBaseModule`: where `Width`, `Height` and `Origin` live.
#[derive(Clone)]
struct Base {
    width: i64,
    height: i64,
    origin: (i64, i64),
}

/// `TileObjectCoordinatesModule`, including the memoised results of `Calculate`.
#[derive(Clone)]
struct Coords {
    width: i64,
    heights: Vec<i64>,
    padding: i64,
    pad_fix: (i64, i64),
    style_width: i64,
    style_height: i64,
    calculated: bool,
}

/// `TileObjectStyleModule`. Note that `styleLineSkip` starts at 1, not 0: `SetupBaseObject` never
/// assigns it, so the module constructor's own default is what every tile inherits.
#[derive(Clone)]
struct StyleMod {
    style: i64,
    horizontal: bool,
    wrap_limit: i64,
    multiplier: i64,
    line_skip: i64,
}

/// One `TileObjectData`. The three modules are shared by reference exactly as the game shares
/// them, and `own_*` is its `_hasOwn*`: false means the next write clones first.
#[derive(Clone)]
struct Obj {
    base: Rc<RefCell<Base>>,
    coords: Rc<RefCell<Coords>>,
    style: Rc<RefCell<StyleMod>>,
    own_base: bool,
    own_coords: bool,
    own_style: bool,
    subtiles: Vec<Option<Obj>>,
    own_subtiles: bool,
}

/// The copy-on-write half of every setter: a private copy of a module that was shared until now.
fn detach<T: Clone>(shared: &Rc<RefCell<T>>) -> Rc<RefCell<T>> {
    let own = shared.borrow().clone();
    Rc::new(RefCell::new(own))
}

impl Obj {
    /// `SetupBaseObject`: the one object built from nothing.
    fn base_object() -> Obj {
        Obj {
            base: Rc::new(RefCell::new(Base {
                width: 1,
                height: 1,
                origin: (0, 0),
            })),
            coords: Rc::new(RefCell::new(Coords {
                width: 0,
                heights: vec![16],
                padding: 0,
                pad_fix: (0, 0),
                style_width: 0,
                style_height: 0,
                calculated: false,
            })),
            style: Rc::new(RefCell::new(StyleMod {
                style: 0,
                horizontal: false,
                wrap_limit: 0,
                multiplier: 1,
                line_skip: 1,
            })),
            own_base: true,
            own_coords: true,
            own_style: true,
            subtiles: Vec::new(),
            own_subtiles: true,
        }
    }

    /// `new TileObjectData(_baseObject)`: a fresh object that shares the base's modules and owns
    /// none of them.
    fn from(parent: &Obj) -> Obj {
        let mut fresh = parent.clone();
        fresh.own_base = false;
        fresh.own_coords = false;
        fresh.own_style = false;
        fresh.subtiles = Vec::new();
        fresh.own_subtiles = false;
        fresh
    }

    /// `CopyFrom`: reference assignment, and deliberately without touching `own_*`.
    fn copy_from(&mut self, other: &Obj) {
        self.base = Rc::clone(&other.base);
        self.coords = Rc::clone(&other.coords);
        self.style = Rc::clone(&other.style);
    }

    fn full_copy_from(&mut self, other: &Obj) {
        self.copy_from(other);
        self.subtiles = other.subtiles.clone();
        self.own_subtiles = true;
    }

    fn set_width(&mut self, value: i64) {
        if !self.own_base {
            if self.base.borrow().width == value {
                return;
            }
            self.clone_base();
        }
        self.base.borrow_mut().width = value;
    }

    fn set_height(&mut self, value: i64) {
        if !self.own_base {
            if self.base.borrow().height == value {
                return;
            }
            self.clone_base();
        }
        self.base.borrow_mut().height = value;
    }

    fn set_origin(&mut self, value: (i64, i64)) {
        if !self.own_base {
            if self.base.borrow().origin == value {
                return;
            }
            // `Origin` does not drag the coordinate module with it; only `Width` and `Height` do.
            self.base = detach(&self.base);
            self.own_base = true;
        }
        self.base.borrow_mut().origin = value;
    }

    /// The `Width`/`Height` copy-on-write, which also forces a private coordinate module and
    /// clears `calculated`, because `Calculate` reads `Width` (`TileObjectData.cs:1194-1200`).
    fn clone_base(&mut self) {
        self.base = detach(&self.base);
        self.own_base = true;
        if !self.own_coords {
            self.coords = detach(&self.coords);
            self.own_coords = true;
            self.coords.borrow_mut().calculated = false;
        }
    }

    fn set_coord(&mut self, field: &str, value: &Value) {
        {
            let coords = self.coords.borrow();
            let same = match field {
                "CoordinateWidth" => coords.width == value.int(),
                "CoordinatePadding" => coords.padding == value.int(),
                "CoordinatePaddingFix" => coords.pad_fix == value.point(),
                "CoordinateHeights" => coords.heights == value.ints(),
                _ => unreachable!("{field}"),
            };
            if !self.own_coords && same {
                return;
            }
        }
        if !self.own_coords {
            self.coords = detach(&self.coords);
            self.own_coords = true;
        }
        let mut coords = self.coords.borrow_mut();
        match field {
            "CoordinateWidth" => coords.width = value.int(),
            "CoordinatePadding" => coords.padding = value.int(),
            "CoordinatePaddingFix" => coords.pad_fix = value.point(),
            "CoordinateHeights" => coords.heights = value.ints(),
            _ => unreachable!("{field}"),
        }
        coords.calculated = false;
    }

    fn set_style(&mut self, field: &str, value: &Value) {
        {
            let style = self.style.borrow();
            let same = match field {
                "Style" => style.style == value.int(),
                "StyleHorizontal" => style.horizontal == value.flag(),
                "StyleWrapLimit" => style.wrap_limit == value.int(),
                "StyleMultiplier" => style.multiplier == value.int(),
                "StyleLineSkip" => style.line_skip == value.int(),
                _ => unreachable!("{field}"),
            };
            if !self.own_style && same {
                return;
            }
        }
        if !self.own_style {
            self.style = detach(&self.style);
            self.own_style = true;
        }
        let mut style = self.style.borrow_mut();
        match field {
            "Style" => style.style = value.int(),
            "StyleHorizontal" => style.horizontal = value.flag(),
            "StyleWrapLimit" => style.wrap_limit = value.int(),
            "StyleMultiplier" => style.multiplier = value.int(),
            "StyleLineSkip" => style.line_skip = value.int(),
            _ => unreachable!("{field}"),
        }
    }

    fn calculate(&self) {
        let width = self.base.borrow().width;
        let mut coords = self.coords.borrow_mut();
        if coords.calculated {
            return;
        }
        coords.calculated = true;
        coords.style_width = (coords.width + coords.padding) * width + coords.pad_fix.0;
        let total: i64 = coords.heights.iter().map(|h| h + coords.padding).sum();
        coords.style_height = total + coords.pad_fix.1;
    }
}

/// A right-hand side this interpreter understands. Anything else (anchors, hooks, draw offsets)
/// parses to [`Value::Other`] and is dropped, because no field of the emitted table reads it.
enum Value {
    Int(i64),
    Flag(bool),
    Point(i64, i64),
    Ints(Vec<i64>),
    Other,
}

impl Value {
    fn int(&self) -> i64 {
        match self {
            Value::Int(n) => *n,
            _ => panic!("not an integer"),
        }
    }

    fn flag(&self) -> bool {
        match self {
            Value::Flag(b) => *b,
            _ => panic!("not a bool"),
        }
    }

    fn point(&self) -> (i64, i64) {
        match self {
            Value::Point(x, y) => (*x, *y),
            _ => panic!("not a Point16"),
        }
    }

    fn ints(&self) -> Vec<i64> {
        match self {
            Value::Ints(v) => v.clone(),
            _ => panic!("not an int array"),
        }
    }
}

/// Fold the method body into one logical statement per entry.
///
/// Multi-line array and `Rectangle[,]` initialisers are the only continuations in `Initialize`,
/// and every one of them ends in `;`, so accumulating until a semicolon lands is enough. The
/// braces inside such an initialiser get swallowed with it, which is the point: they must not
/// reach the block walker as if they opened a scope.
fn statements(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut pending = String::new();
    for raw in body.lines() {
        let line = raw.trim();
        if line.is_empty() {
            continue;
        }
        if pending.is_empty() && (line == "{" || line == "}" || line.starts_with("for (")) {
            out.push(line.to_string());
            continue;
        }
        if !pending.is_empty() {
            pending.push(' ');
        }
        pending.push_str(line);
        if pending.ends_with(';') {
            out.push(std::mem::take(&mut pending));
        }
    }
    assert!(pending.is_empty(), "statement never terminated: {pending}");
    out
}

