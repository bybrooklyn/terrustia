//! `crates/terrustia-proto/src/tile_object.rs`: how big each placeable object is and how its
//! styles are laid out in the sheet.
//!
//! Every other table in this crate is read off a declaration. This one is not: `TileObjectData
//! .Initialize` (`Terraria.ObjectData/TileObjectData.cs:2111-5015`) is a 2,900-line *program* that
//! mutates one shared "current object" field by field and stamps it into a slot with `addTile(N)`,
//! then keeps mutating the next one from a fresh base. There is nothing to read off. The only way
//! to get the end state is to run it, so this module is a small interpreter for the statement
//! vocabulary that method actually uses.
//!
//! Four details decide whether the interpretation is right, and a plausible shortcut gets each one
//! wrong:
//!
//! * **`addTile` resets the current object.** Each of `addTile`/`addBaseTile` ends with
//!   `newTile = new TileObjectData(_baseObject)` (`:2009-2014`), so a tile inherits the *base*
//!   defaults and never its predecessor's. Reading `Initialize` as one running accumulator is the
//!   tempting misreading, and it silently gives an entry whatever the tile before it last set.
//! * **`CopyFrom` shares module references rather than copying them** (`:1698-1715`). Writes go
//!   through a copy-on-write guarded by `_hasOwn*`, and `CopyFrom` leaves those flags alone, so an
//!   object that already owns a module and is then `CopyFrom`'d keeps the flag and writes straight
//!   through into what it copied from. Value semantics get this wrong, so the modules here are
//!   `Rc<RefCell<_>>` and are shared exactly as the game shares them.
//! * **A setter handed the value already in place returns early**, before the copy-on-write and
//!   before `calculated = false`. `CoordinatePadding = 2` on something already at 2 is not the same
//!   no-op as skipping the line: it leaves a stale `calculated` behind.
//! * **`Calculate` is memoised on the coordinate module** (`:1805-1811`) while the `Width` it reads
//!   lives in the *base* module. Setting `Width` clears `calculated` only when the object did not
//!   already own its base module (`:1186-1201`). That asymmetry is observable in the shipped
//!   numbers.
//!
//! Only the per-type entry is emitted. Vanilla also carries sub-tiles (per style) and alternates
//! (per placement direction); they are interpreted here because `FullCopyFrom` reads a style-0
//! sub-tile, but they are not part of the table and the emitted header says so.

