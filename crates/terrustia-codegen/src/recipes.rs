/// D1: `AddCritterStatueRecipe` (`Recipe.cs` 16702-16718), called 22 times from `SetupRecipes`
/// (9630-9651):
///
/// ```text
/// private static void AddCritterStatueRecipe(int statueItem, int critterItem = 0, RecipeGroup critterGroup = null)
/// {
///     currentRecipe.createItem.SetDefaults(statueItem);
///     currentRecipe.requiredItem[0].SetDefaults(3);
///     currentRecipe.requiredItem[0].stack = 50;
///     if (critterGroup != null)
///     {
///         critterItem = critterGroup.GetPlaceholderItemType();
///         currentRecipe.RequireGroup(critterGroup);
///     }
///     currentRecipe.requiredItem[1].SetDefaults(critterItem);
///     currentRecipe.requiredItem[1].stack = 5;
///     currentRecipe.requiredTile = 283;
///     AddRecipe();
/// }
/// ```
///
/// Every statue is fifty Stone Block (3) plus five of the critter. Fourteen calls pass a literal
/// critter item; eight pass a `RecipeGroup` instead (`RecipeGroups.Squirrels`, `.Butterflies`, …),
/// and the helper resolves that to the group's *first* member: `RecipeGroup.GetPlaceholderItemType`
/// returns `Items[0]` (`RecipeGroup.cs` 101-104), the same item the group was first constructed
/// with (`SetupRecipeGroups`, `Recipe.cs` 497-533). This reads that first member straight out of
/// `SetupRecipeGroups`'s source rather than hard-coding the twelve resolved ids, so it stays correct
/// if a group's member order ever changes.
fn critter_statues(src: &str, body: &str) -> Vec<RecipeData> {
    let group_re = Regex::new(r"RecipeGroups\.(\w+) = new RecipeGroup\([^,]+,\s*(\d+)").unwrap();
    let placeholders: BTreeMap<String, u32> = group_re
        .captures_iter(src)
        .map(|c| (c[1].to_string(), c[2].parse().unwrap()))
        .collect();
    assert!(
        placeholders.len() >= 20,
        "only {} recipe groups parsed; SetupRecipeGroups's shape changed",
        placeholders.len()
    );

    let call_re = Regex::new(r"AddCritterStatueRecipe\(([^)]*)\);").unwrap();
    let calls: Vec<Vec<String>> = call_re
        .captures_iter(body)
        .map(|c| c[1].split(',').map(|s| s.trim().to_string()).collect())
        .collect();
    assert_eq!(
        calls.len(),
        22,
        "expected 22 AddCritterStatueRecipe calls; Recipe.cs's shape changed"
    );

    calls
        .into_iter()
        .map(|args| {
            let statue: u32 = args[0].parse().unwrap();
            let critter = match args.get(2) {
                Some(group) => {
                    let name = group.trim_start_matches("RecipeGroups.");
                    *placeholders
                        .get(name)
                        .unwrap_or_else(|| panic!("unknown recipe group {name}"))
                }
                None => args[1].parse().unwrap(),
            };
            plain_recipe(statue, 1, vec![(3, 50), (critter, 5)])
        })
        .collect()
}

