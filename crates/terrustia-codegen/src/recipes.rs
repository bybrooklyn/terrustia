//! `crates/terrustia-proto/src/recipes.rs` — what each crafted item is made of, for shimmer
//! decrafting. Ported from `gen_recipes.py`.
//!
//! Reads `Recipe.SetupRecipes`, one recipe per `createItem.SetDefaults(N) … AddRecipe()`, keeps the
//! last decraftable recipe for each result (`UpdateWhichItemsAreCrafted`), and packs the
//! ingredients end to end.
//!
//! D1: `SetupRecipes` also builds around 570 more recipes inside `for` loops and a handful of small
//! per-set helper functions (`AddCritterStatueRecipe`, `AddStandardFurnitureSetRecipes`), none of
//! which the literal `createItem.SetDefaults(N)` parse above can see: their argument is a loop
//! variable, an array slot, or a helper parameter, never a source-text digit. [`loop_built_recipes`]
//! unrolls each of these families by hand against the cited `Recipe.cs` lines and its doc comment
//! is the inventory of what they are and why each is faithful.

use std::collections::BTreeMap;
use std::ops::Range;
