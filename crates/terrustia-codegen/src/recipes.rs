/// D1: every loop- and helper-built recipe family `SetupRecipes` constructs, unrolled and
/// concatenated. `CreateReverseWallRecipes` and `CreateReversePlatformRecipes` (`Recipe.cs` 16744
/// and 16720, called from `SetupRecipes` at 15148-15149) build recipes the same programmatic way
/// but are deliberately excluded: both mark every recipe they add `notDecraftable = true`
/// immediately after `AddRecipe()`, so however many they add, none is ever decraftable; unrolling
/// them would add source and tests for zero table rows.
///
/// None of the ten families here shares a result item with any other family, nor with any of the
/// literal recipes `chunk_re` already parses in [`generate`] (checked by hand against every id each
/// produces), except `StrungCounterweight`, whose one collision is with `chunk_re`'s own spurious
/// partial match, which [`generate`] excludes before calling this function. So simple
/// concatenation, in the order the families appear below, is enough for `UpdateWhichItemsAreCrafted`'s
/// last-wins fold to land on the same recipe the game would.
fn loop_built_recipes(root: &Path, src: &str, body: &str) -> Vec<RecipeData> {
    let mut out = Vec::new();
    out.extend(fake_chest_texture_copies(root, body));
    out.extend(fake_chest_array(body));
    out.extend(blacksmith_racks(body));
    out.extend(strung_counterweight_loop(body).1);
    out.extend(alphabet_statues(body));
    out.extend(critter_statues(src, body));
    out.extend(butterfly_jars(body));
    out.extend(dragonfly_jars(body));
    out.extend(gemspark_wall_variants(body));
    out.extend(standard_furniture_sets(body));
    out
}

/// Emit an ascending `static NAME: [(u16, u16); N]` index table. `cargo fmt` reflows the rows.
fn index_table(name: &str, rows: &[(u32, u32)], doc: &str) -> String {
    let body: Vec<String> = rows.iter().map(|&(a, b)| format!("({a},{b}),")).collect();
    format!(
        "{doc}\nstatic {name}: [(u16, u16); {}] = [\n    {}\n];",
        rows.len(),
        body.join(" ")
    )
}

pub fn generate(root: &Path) -> String {
    let src = read_lossy(&root.join("Terraria/Recipe.cs"));
    let start = src
        .find("public static void SetupRecipes()")
        .expect("SetupRecipes not found");
    let body = &src[start..];
    // The literal-text scan below reads the resolved copy; `loop_built_recipes` keeps the raw one,
    // because its per-family regexes match `SetupRecipes`' own loop and helper text verbatim.
    let resolved = resolve_recipe_locals(body);

    let chunk_re =
        Regex::new(r"(?s)currentRecipe\.createItem\.SetDefaults\((\d+)\);(.*?)AddRecipe\(\);")
            .unwrap();
    let stack_re = Regex::new(r"createItem\.stack = (\d+)").unwrap();

    // D1: the StrungCounterweight loop's one copy of source text is a spurious match for
    // `chunk_re` above (see `strung_counterweight_loop`'s doc comment): it has a literal
    // `createItem`, but a loop-variable `requiredItem[1]` that the generic ingredient parse can't
    // see, so left in it would produce a real but wrong single-ingredient recipe. Exclude it here;
    // `loop_built_recipes` supplies the correct six recipes instead.
    let (strung_exclude, _) = strung_counterweight_loop(&resolved);

    let mut recipes: Vec<RecipeData> = Vec::new();
    for cap in chunk_re.captures_iter(&resolved) {
        if strung_exclude.contains(&cap.get(0).unwrap().start()) {
            continue;
        }
        let result: u32 = cap[1].parse().unwrap();
        let text = &cap[2];
        let stack = stack_re.captures(text).map_or(1, |m| m[1].parse().unwrap());
        recipes.push(RecipeData {
            result,
            stack,
            ingredients: ingredients_of(text),
            not_decraftable: text.contains("notDecraftable = true")
                || text.contains("DisableDecraft()"),
            crimson: text.contains("crimson = true")
                || text.contains(".AddCondition(Condition.InCrimson"),
            corruption: text.contains("corruption = true")
                || text.contains(".AddCondition(Condition.InCorruption"),
            // `Recipe.AddRecipe` (`Recipe.cs:16795-16800`) sets `alchemy` itself, from the
            // crafting station: `if (currentRecipe.requiredTile == 13) currentRecipe.alchemy =
            // true;` (tile 13 is the Bottle/Alchemy Table). The literal `alchemy = true` never
            // appears anywhere in `SetupRecipes`, so looking for it left the flag false on all
            // 3,098 rows and shimmer-decrafting a potion returned every ingredient instead of
            // losing one in three: a free material duplicator, which is exactly what the flag
            // exists to prevent. Both spellings of the assignment count.
            alchemy: text.contains("requiredTile = 13;") || text.contains("SetCraftingStation(13)"),
        });
    }
    assert!(
        recipes.len() >= 1000,
        "only {} recipes parsed; SetupRecipes' shape changed",
        recipes.len()
    );

    // D1: the ~570 recipes `SetupRecipes` builds inside `for` loops and small per-set helper
    // functions, invisible to `chunk_re` above. See `loop_built_recipes`'s doc comment for the full
    // family inventory and why appending them here (rather than interleaving by source position) is
    // safe.
    recipes.extend(loop_built_recipes(root, &src, body));
    assert!(
        recipes.len() >= 3200,
        "only {} recipes total after adding the loop-built families; a family's regex stopped \
         matching (Recipe.cs's shape changed) rather than the extraction actually shrinking",
        recipes.len()
    );

    // `UpdateWhichItemsAreCrafted`: the last decraftable recipe for a result wins.
    let mut is_crafted: BTreeMap<u32, usize> = BTreeMap::new();
    let mut crimson_of: BTreeMap<u32, usize> = BTreeMap::new();
    let mut corruption_of: BTreeMap<u32, usize> = BTreeMap::new();
    for (index, r) in recipes.iter().enumerate() {
        if r.ingredients.is_empty() {
            continue;
        }
        if !r.not_decraftable {
            is_crafted.insert(r.result, index);
        }
        if r.crimson {
            crimson_of.insert(r.result, index);
        }
        if r.corruption {
            corruption_of.insert(r.result, index);
        }
    }

    let mut used: Vec<usize> = is_crafted
        .values()
        .chain(crimson_of.values())
        .chain(corruption_of.values())
        .copied()
        .collect();
    used.sort_unstable();
    used.dedup();
    let renumber: BTreeMap<usize, usize> = used
        .iter()
        .enumerate()
        .map(|(new, &old)| (old, new))
        .collect();

    // Pack ingredients end to end and lay out the recipes in kept order.
    let mut flat: Vec<(u32, u32)> = Vec::new();
    let mut recipe_rows: Vec<String> = Vec::new();
    for &old in &used {
        let r = &recipes[old];
        let first = flat.len();
        flat.extend(r.ingredients.iter().copied());
        recipe_rows.push(format!(
            "    Recipe {{ result: {}, makes: {}, first: {first}, count: {}, alchemy: {} }},",
            r.result,
            r.stack,
            r.ingredients.len(),
            r.alchemy
        ));
    }

    let ingredients_rows: Vec<String> = flat.iter().map(|&(i, s)| format!("({i},{s}),")).collect();
    let ingredients_block = format!(
        "/// Every decraftable recipe's ingredients, packed end to end.\n\
         ///\n\
         /// `static` rather than `const`: a `const` of this size is copied at every use site.\n\
         static INGREDIENTS: [Ingredient; {}] = [\n    {}\n];",
        flat.len(),
        ingredients_rows.join(" ")
    );
    let recipes_block = format!(
        "/// The recipes themselves, in the game's own order.\nstatic RECIPES: [Recipe; {}] = [\n{}\n];",
        used.len(),
        recipe_rows.join("\n")
    );

    let renumbered = |mapping: &BTreeMap<u32, usize>| -> Vec<(u32, u32)> {
        let mut rows: Vec<(u32, u32)> = mapping
            .iter()
            .filter_map(|(&item, old)| renumber.get(old).map(|&new| (item, new as u32)))
            .collect();
        rows.sort_unstable();
        rows
    };
    let crafted_by = index_table(
        "CRAFTED_BY",
        &renumbered(&is_crafted),
        "/// Which recipe makes each craftable item. `ItemID.Sets.IsCrafted`.",
    );
    let crafted_by_crimson = index_table(
        "CRAFTED_BY_CRIMSON",
        &renumbered(&crimson_of),
        "/// ...and the crimson-world variant, where one exists.",
    );
    let crafted_by_corruption = index_table(
        "CRAFTED_BY_CORRUPTION",
        &renumbered(&corruption_of),
        "/// ...and the corruption one.",
    );

    format!(
        "{HEADER}\n\n{ingredients_block}\n\n{recipes_block}\n\n{crafted_by}\n\n{crafted_by_crimson}\n\n{crafted_by_corruption}\n\n{TAIL}\n"
    )
}
